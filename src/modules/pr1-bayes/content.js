export function problemStatement(v) {
  const present = v.features.filter((_, j) => v.observed[j]).map((f) => f.split(' — ')[0]);
  const absent = v.features.filter((_, j) => !v.observed[j]).map((f) => f.split(' — ')[0]);
  return `Об'єкт діагностування — <b>${v.object}</b>. Можливі технічні стани: ${v.states.map((s) => `<i>${s}</i>`).join('; ')}. `
    + `Діагностичні ознаки: ${v.features.map((f) => `<i>${f}</i>`).join('; ')}. `
    + `За результатами обстеження ${present.length ? `виявлено ознаки ${present.join(', ')}` : 'жодної ознаки не виявлено'}${absent.length ? `; ознаки ${absent.join(', ')} відсутні` : ''}. `
    + `Вважаючи ознаки діагностично незалежними, визначте апостеріорні ймовірності станів, найбільш імовірний стан і прийміть рішення про діагноз за порогу розпізнавання P<sub>l</sub> = ${String(v.threshold).replace('.', ',')}.`;
}

